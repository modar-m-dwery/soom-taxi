"""
سجلّ أنواع إشارات الغش — ما تعرفه الشيفرة عن كلّ نمط تلاعب.

كلّ نوع: رمزٌ ثابت يُخزَّن مع الإشارة، اسمٌ يقرؤه المراجع، على مَن يقع
(سائق/زبون/أيّهما)، ووزنٌ يُضاف إلى نقاط الخطر قبل التلاشي، ونصيحةٌ تقول
للمراجع ما الذي يفحصه قبل أن يحكم.

الأوزان مختارة بحيث لا تكفي إشارةٌ واحدة لتقييد حساب: أقوى إشارة (35)
تضع صاحبها «تحت المراقبة» فقط. التقييد (70) يحتاج نمطين قويّين أو تكرارًا
— لأنّ عائلةً تتشارك هاتفًا، أو سائقًا في نفق فقد الـGPS، ليسوا محتالين.

نوعٌ جديد = سطر `register(...)` هنا وكاشفٌ يستدعي `IntegrityService.record`
— لا ترحيل ولا تعديل في النماذج.
"""

from dataclasses import dataclass


class Role:
    DRIVER = "driver"
    CUSTOMER = "customer"
    ANY = "any"


@dataclass(frozen=True)
class SignalKind:
    code: str
    label: str
    role: str
    weight: int
    advice: str = ""


KINDS: dict[str, SignalKind] = {}


def register(kind: SignalKind) -> SignalKind:
    KINDS[kind.code] = kind
    return kind


def get(code: str) -> SignalKind:
    return KINDS[code]


def choices():
    return [(k.code, k.label) for k in KINDS.values()]


