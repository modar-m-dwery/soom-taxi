"""
منحنيات الطلب والعرض لمدينة سوريّة صغيرة (جبلة افتراضًا).

الأرقام أوزانٌ نسبيّة لكلّ ساعة (1.0 = ساعة عاديّة)، مبنيّة على نمط
المدن الساحليّة: ذروة الدوام صباحًا، وذروة خروج المدارس والدوائر ظهرًا،
وذروة المساء الأطول، وليلة الخميس (بداية العطلة) أثقل، وصباح الجمعة
خفيف. ورمضان نمطٌ مختلف كلّيًّا: الطلب يتكدّس قبل الإفطار بساعة، ويكاد
ينعدم أثناءه، ثمّ ذروة ثانية بعد التراويح، وذروة صغيرة للسحور.
"""

NORMAL = [
    0.15, 0.10, 0.08, 0.06, 0.06, 0.12,   # 00–05
    0.50, 1.40, 1.80, 1.10, 0.80, 0.80,   # 06–11 ذروة الدوام 7–9
    0.90, 1.50, 1.60, 1.20, 1.00, 1.40,   # 12–17 خروج المدارس والدوائر 13–15
    1.70, 1.50, 1.30, 1.10, 0.80, 0.40,   # 18–23 ذروة المساء
]

RAMADAN = [
    0.30, 0.45, 0.60, 0.35, 0.10, 0.05,   # 00–05 سحور حول الثانية
    0.10, 0.40, 0.70, 0.70, 0.60, 0.60,   # 06–11 دوامٌ أقصر وأخفّ
    0.80, 1.20, 1.10, 0.90, 1.30, 2.20,   # 12–17 ذروة ما قبل الإفطار 17
    2.00, 0.25, 0.60, 1.80, 1.70, 1.00,   # 18–23 الإفطار 19 ثمّ ما بعد التراويح
]

# (بداية، نهاية، نصيب السائقين) — النهاية بعد منتصف الليل تُكتب > 24.
SHIFTS = [
    (6, 14, 0.30),    # صباحيّ: موظّفون يعملون قبل الدوام وبعده
    (14, 23, 0.30),   # مسائيّ
    (8, 20, 0.25),    # يوم كامل
    (18, 26, 0.15),   # ليليّ حتّى الثانية
]


def demand_weight(hour, weekday, ramadan=False):
    """weekday بتقويم بايثون: 3 = الخميس، 4 = الجمعة."""
    curve = RAMADAN if ramadan else NORMAL
    weight = curve[hour % 24]
    if not ramadan:
        if weekday == 3 and hour >= 19:
            weight *= 1.3          # ليلة الخميس
        if weekday == 4 and hour < 12:
            weight *= 0.4          # صباح الجمعة
    return weight


def on_shift(shift, hour):
    start, end, _ = shift
    return start <= hour < end or start <= hour + 24 < end
